void FMetaXRAcousticMapSceneProxy::GetDynamicMeshElements(
    const TArray<const FSceneView*>& Views,
    const FSceneViewFamily& ViewFamily,
    uint32 VisibilityMap,
    FMeshElementCollector& Collector) const {
  FColoredMaterialRenderProxy* RedMaterial =
      new FColoredMaterialRenderProxy(GEngine->LevelColorationUnlitMaterial->GetRenderProxy(), FLinearColor::Red);
  FColoredMaterialRenderProxy* YellowMaterial =
      new FColoredMaterialRenderProxy(GEngine->LevelColorationUnlitMaterial->GetRenderProxy(), FLinearColor::Yellow);
  Collector.RegisterOneFrameMaterialProxy(RedMaterial);
  Collector.RegisterOneFrameMaterialProxy(YellowMaterial);

  for (int32 ViewIndex = 0; ViewIndex < Views.Num(); ViewIndex++) {
    if (VisibilityMap & (1 << ViewIndex)) {
      const FSceneView* View = Views[ViewIndex];
      if (!AcousticMapComponent->GizmoVertices.IsEmpty() && !AcousticMapComponent->GizmoIndices.IsEmpty()) {
        // Draw all the points in yellow
        FDynamicMeshBuilder MeshBuilder(View->GetFeatureLevel());
        MeshBuilder.AddVertices(AcousticMapComponent->GizmoVertices);
        MeshBuilder.AddTriangles(AcousticMapComponent->GizmoIndices);
        MeshBuilder.GetMesh(
            FMatrix::Identity, // The transforms are applied during RefreshSphereGizmo()
            YellowMaterial,
            SDPG_World,
            true,
            false,
            false,
            ViewIndex,
            Collector);
      }

      // If there is a selected point, draw it in red
      if (!AcousticMapComponent->GizmoVertices.IsEmpty() && !AcousticMapComponent->GizmoSelectedIndices.IsEmpty()) {
        FDynamicMeshBuilder SelectedMeshBuilder(View->GetFeatureLevel());
        SelectedMeshBuilder.AddVertices(AcousticMapComponent->GizmoVertices);
        SelectedMeshBuilder.AddTriangles(AcousticMapComponent->GizmoSelectedIndices);
        SelectedMeshBuilder.GetMesh(
            FMatrix::Identity, // The transforms are applied during RefreshSphereGizmo()
            RedMaterial,
            SDPG_World,
            true,
            false,
            false,
            ViewIndex,
            Collector);
      }
    }
  }
}
