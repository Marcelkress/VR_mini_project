FVector UMetaXRAcousticMap::GetNewPointForRay(FVector RayOrigin, FVector RayDirection) {
  float DefaultDistance = 400.0f; // How far away to place a point if the ray hits nothing
  float TraceDistance = 60000.0f; // How far away to fire the ray trace before giving up
  FVector EndPosition = RayOrigin + (RayDirection * TraceDistance); // The point at the end of our longest possible ray

  // Try to perform raytracing to find a point in front of the camera that is not blocked by geometry.
  FVector NewPointPosition;
  UWorld* World = GetWorld();
  if (World != nullptr) {
    // Setup variables for unreal's raytracing function
    FHitResult HitResult;
    FCollisionObjectQueryParams ObjectTypes;
    ObjectTypes.AddObjectTypesToQuery(ECC_WorldStatic);
    ObjectTypes.AddObjectTypesToQuery(ECC_WorldDynamic);
    FCollisionQueryParams QueryParams;

    // Perform a single raytrace which will tell us the first blocking hit.
    bool HitFound = World->LineTraceSingleByObjectType(HitResult, RayOrigin, EndPosition, ObjectTypes, QueryParams);
    if (HitResult.bBlockingHit && IsValid(HitResult.GetActor())) {
      // Place the point slightly away from the hit point to avoid placing points on walls.
      float bias = 300.0f;
      NewPointPosition = RayOrigin + (RayDirection * FMath::Max(HitResult.Distance - bias, 0.0f));

      if (bNoFloating == false) {
        return NewPointPosition;
      }

      // Trace two rays down and up to place the point at the right height.
      FVector DownRayEndPosition = NewPointPosition + (GravityVector.GetUnsafeNormal() * TraceDistance);
      if (World->LineTraceSingleByObjectType(HitResult, NewPointPosition, DownRayEndPosition, ObjectTypes, QueryParams)) {
        float downDistance = HitResult.Distance;
        float targetHeight = NewPointPosition.Z;

        if (downDistance > MaxHeight) {
          targetHeight = HeadHeight;
        } else if (downDistance < HeadHeight) {
          FVector UpRayEndPosition = NewPointPosition - (GravityVector.GetUnsafeNormal() * TraceDistance);
          if (World->LineTraceSingleByObjectType(HitResult, NewPointPosition, UpRayEndPosition, ObjectTypes, QueryParams)) {
            // Move point so that it is either at head height or is at the floor/ceiling midpoint if that is less.
            float midHeight = 0.5f * (downDistance + HitResult.Distance);
            targetHeight = FMath::Min(HeadHeight, midHeight);
          }
        }

        // height adjustment
        NewPointPosition += GravityVector * (downDistance - targetHeight);
      }
      return NewPointPosition;
    } else {
      // Facing empty space, place the point slightly in front of the camera.
      return RayOrigin + (RayDirection * DefaultDistance);
    }
  }

  // Place slightly in front of camera as fallback if cannot raytrace or we didn't hit anything
  return RayOrigin + (RayDirection * DefaultDistance);
}

void UMetaXRAcousticMap::SetupSphereVertices() {
  if (!SphereVertices.IsEmpty() && !SphereIndices.IsEmpty()) {
    return;
  }

  for (uint32_t Stack = 0; Stack <= META_XR_AUDIO_MAP_SPHERE_NUM_STACKS; ++Stack) {
    for (uint32_t Slice = 0; Slice <= META_XR_AUDIO_MAP_SPHERE_NUM_SLICES; ++Slice) {
      const float XSegment = static_cast<float>(Slice) / static_cast<float>(META_XR_AUDIO_MAP_SPHERE_NUM_SLICES);
      const float YSegment = static_cast<float>(Stack) / static_cast<float>(META_XR_AUDIO_MAP_SPHERE_NUM_STACKS);
      const float XPos = FMath::Cos(XSegment * 2 * PI) * FMath::Sin(YSegment * PI);
      const float YPos = FMath::Cos(YSegment * PI);
      const float ZPos = FMath::Sin(XSegment * 2 * PI) * FMath::Sin(YSegment * PI);
      SphereVertices.Add(FVector(XPos, YPos, ZPos));
    }
  }

  for (uint32_t Stack = 0; Stack < META_XR_AUDIO_MAP_SPHERE_NUM_STACKS; ++Stack) {
    for (uint32_t Slice = 0; Slice < META_XR_AUDIO_MAP_SPHERE_NUM_SLICES; ++Slice) {
      SphereIndices.Add((Stack + 1) * (META_XR_AUDIO_MAP_SPHERE_NUM_SLICES + 1) + Slice);
      SphereIndices.Add(Stack * (META_XR_AUDIO_MAP_SPHERE_NUM_SLICES + 1) + Slice);
      SphereIndices.Add(Stack * (META_XR_AUDIO_MAP_SPHERE_NUM_SLICES + 1) + Slice + 1);

      SphereIndices.Add((Stack + 1) * (META_XR_AUDIO_MAP_SPHERE_NUM_SLICES + 1) + Slice);
      SphereIndices.Add(Stack * (META_XR_AUDIO_MAP_SPHERE_NUM_SLICES + 1) + Slice + 1);
      SphereIndices.Add((Stack + 1) * (META_XR_AUDIO_MAP_SPHERE_NUM_SLICES + 1) + Slice + 1);
    }
  }
}

int UMetaXRAcousticMap::GetNumPoints() const {
  return PointsOVR.Num();
}

void UMetaXRAcousticMap::AddPoint(FVector PointUE) {
  PointsOVR.Add(MetaXRAudioUtilities::ToOVRVector(GetComponentTransform().Inverse().TransformPosition(PointUE)));
  RefreshSphereGizmo();
}

void UMetaXRAcousticMap::RemovePoint(int SelectedPoint) {
  PointsOVR.RemoveAt(SelectedPoint);
  RefreshSphereGizmo();
}

void UMetaXRAcousticMap::RemoveSelectedPoint() {
  PointsOVR.RemoveAt(SelectedPointIndex);
  ResetSelectedPoint();
  RefreshSphereGizmo();
}

void UMetaXRAcousticMap::MoveSelectedPoint(FVector NewLocationUE) {
  if (!PointIsSelected())
    return;
  PointsOVR[SelectedPointIndex] = MetaXRAudioUtilities::ToOVRVector(GetComponentTransform().Inverse().TransformPosition(NewLocationUE));
  RefreshSphereGizmo();
}

void UMetaXRAcousticMap::SetPoints(TArray<float> NewPointsOVR, int NumPoints) {
  PointsOVR.SetNumUninitialized(NumPoints);
  for (int32 i = 0; i < NumPoints; i++) {
    FVector Point;
    Point.X = NewPointsOVR[i * 3];
    Point.Y = NewPointsOVR[i * 3 + 1];
    Point.Z = NewPointsOVR[i * 3 + 2];
    PointsOVR[i] = Point;
  }
  RefreshSphereGizmo();
}

FVector UMetaXRAcousticMap::GetPointUE(int SelectedPoint) const {
  return GetComponentTransform().TransformPosition(MetaXRAudioUtilities::ToUEVector(PointsOVR[SelectedPoint]));
}

TArray<FVector> UMetaXRAcousticMap::GetPointsUE() const {
  TArray<FVector> ReturnArray;
  for (int i = 0; i < PointsOVR.Num(); i++) {
    ReturnArray.Add(GetPointUE(i));
  }
  return ReturnArray;
}

FVector UMetaXRAcousticMap::GetSelectedPointUE() const {
  return GetPointUE(SelectedPointIndex);
}

void UMetaXRAcousticMap::SetSelectedPoint(int SelectedPoint) {
  SelectedPointIndex = SelectedPoint;
  RefreshSphereGizmo();
}

void UMetaXRAcousticMap::ResetSelectedPoint() {
  SetSelectedPoint(MAX_int32);
}

bool UMetaXRAcousticMap::PointIsSelected() const {
  return (SelectedPointIndex < PointsOVR.Num() && SelectedPointIndex >= 0);
}

bool UMetaXRAcousticMap::HasPoints() const {
  return !PointsOVR.IsEmpty();
}

void UMetaXRAcousticMap::RefreshSphereGizmo() {
  FDynamicMeshVertex Vertex;
  GizmoSelectedIndices.Empty();
  GizmoVertices.Empty();
  GizmoIndices.Empty();
  for (int i = 0; i < GetNumPoints(); i++) {
    FTransform SphereTransform(FQuat::Identity, GetPointUE(i), FVector(META_XR_AUDIO_MAP_SPHERE_RADIUS));
    for (const FVector& Vert : SphereVertices) {
      Vertex.Position = MetaXRAudioUtilities::VectorToVector3f(SphereTransform.TransformPosition(Vert));
      GizmoVertices.Add(Vertex);
    }
    int IndexOffset = SphereVertices.Num() * i;
    for (const uint32& Index : SphereIndices) {
      // Save the selected point to separate array to render as a different color
      if (i == SelectedPointIndex) {
        GizmoSelectedIndices.Add(Index + IndexOffset);
      } // Save the unselected points to the same array to maximize render speed
      else {
        GizmoIndices.Add(Index + IndexOffset);
      }
    }
  }
}

